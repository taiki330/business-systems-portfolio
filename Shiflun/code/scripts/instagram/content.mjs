/**
 * 投稿するコンテンツを選ぶ
 * 日付ベースでローテーション（DBなしで重複を避ける）
 */
export function selectPost() {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((now - startOfYear) / 86400000);
  const index = dayOfYear % posts.length;
  return posts[index];
}
